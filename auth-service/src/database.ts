import { Injectable, OnModuleDestroy, OnModuleInit } from '@nestjs/common';
import pg, { QueryResultRow } from 'pg';

@Injectable()
export class Database implements OnModuleInit, OnModuleDestroy {
  private readonly pool: pg.Pool;

  constructor() {
    const password = process.env.AUTH_DB_PASSWORD;
    if (!password) {
      throw new Error('AUTH_DB_PASSWORD debe estar configurada.');
    }
    this.pool = new pg.Pool({
      host: process.env.AUTH_DB_HOST ?? 'auth-db',
      port: Number(process.env.AUTH_DB_PORT ?? '5432'),
      database: process.env.AUTH_DB_NAME ?? 'satrural_auth',
      user: process.env.AUTH_DB_USER ?? 'satrural_auth',
      password,
    });
  }

  async onModuleInit(): Promise<void> {
    await this.pool.query(`
      CREATE TABLE IF NOT EXISTS users (
        id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username varchar(255) NOT NULL UNIQUE,
        password_hash text,
        full_name varchar(150) NOT NULL,
        role_id integer NOT NULL CHECK (role_id IN (1, 2, 3)),
        is_active boolean NOT NULL DEFAULT true,
        created_at timestamptz NOT NULL DEFAULT now()
      );
      CREATE TABLE IF NOT EXISTS external_identities (
        provider varchar(30) NOT NULL,
        subject varchar(255) NOT NULL,
        user_id integer NOT NULL REFERENCES users(id),
        PRIMARY KEY (provider, subject)
      );
      CREATE TABLE IF NOT EXISTS oauth_requests (
        state_hash char(64) PRIMARY KEY,
        provider varchar(30) NOT NULL,
        code_verifier varchar(128) NOT NULL,
        nonce varchar(128),
        expires_at timestamptz NOT NULL
      );
      ALTER TABLE oauth_requests ADD COLUMN IF NOT EXISTS nonce varchar(128);
      CREATE TABLE IF NOT EXISTS login_codes (
        code_hash char(64) PRIMARY KEY,
        user_id integer NOT NULL REFERENCES users(id),
        provider varchar(30) NOT NULL,
        expires_at timestamptz NOT NULL
      );
    `);
  }

  query<T extends QueryResultRow>(
    sql: string,
    parameters: unknown[] = [],
  ): Promise<pg.QueryResult<T>> {
    return this.pool.query<T>(sql, parameters);
  }

  async onModuleDestroy(): Promise<void> {
    await this.pool.end();
  }
}
